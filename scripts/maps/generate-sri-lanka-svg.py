#!/usr/bin/env python3

from __future__ import annotations

import json
import math
import sys
import urllib.request
from pathlib import Path
from typing import Any

SOURCE_URL = (
    "https://raw.githubusercontent.com/"
    "martynafford/natural-earth-geojson/master/"
    "10m/cultural/ne_10m_admin_0_countries.json"
)

OUTPUT = Path("public/assets/maps/sri-lanka-network-base.svg")

VIEWBOX_WIDTH = 800
VIEWBOX_HEIGHT = 1200
PADDING = 34


def feature_name(properties: dict[str, Any]) -> str:
    fields = (
        "ADMIN",
        "NAME",
        "NAME_EN",
        "SOVEREIGNT",
        "FORMAL_EN",
        "BRK_NAME",
    )

    for field in fields:
        value = properties.get(field)

        if isinstance(value, str) and value.strip():
            return value.strip()

    return ""


def find_sri_lanka(data: dict[str, Any]) -> dict[str, Any]:
    for feature in data.get("features", []):
        name = feature_name(feature.get("properties", {})).lower()

        if name in {"sri lanka", "sri lanka (ceylon)"}:
            return feature

    raise RuntimeError("Sri Lanka was not found in the Natural Earth dataset.")


def extract_rings(geometry: dict[str, Any]) -> list[list[list[float]]]:
    geometry_type = geometry.get("type")
    coordinates = geometry.get("coordinates", [])

    if geometry_type == "Polygon":
        return coordinates

    if geometry_type == "MultiPolygon":
        rings: list[list[list[float]]] = []

        for polygon in coordinates:
            rings.extend(polygon)

        return rings

    raise RuntimeError(f"Unsupported geometry type: {geometry_type}")


def project_factory(
    rings: list[list[list[float]]],
):
    points = [
        coordinate
        for ring in rings
        for coordinate in ring
        if len(coordinate) >= 2
    ]

    longitudes = [point[0] for point in points]
    latitudes = [point[1] for point in points]

    min_lon = min(longitudes)
    max_lon = max(longitudes)
    min_lat = min(latitudes)
    max_lat = max(latitudes)

    centre_lat = math.radians((min_lat + max_lat) / 2)

    projected_width = (max_lon - min_lon) * math.cos(centre_lat)
    projected_height = max_lat - min_lat

    available_width = VIEWBOX_WIDTH - PADDING * 2
    available_height = VIEWBOX_HEIGHT - PADDING * 2

    scale = min(
        available_width / projected_width,
        available_height / projected_height,
    )

    content_width = projected_width * scale
    content_height = projected_height * scale

    offset_x = (VIEWBOX_WIDTH - content_width) / 2
    offset_y = (VIEWBOX_HEIGHT - content_height) / 2

    def project(lon: float, lat: float) -> tuple[float, float]:
        x = (
            (lon - min_lon)
            * math.cos(centre_lat)
            * scale
            + offset_x
        )

        y = (
            (max_lat - lat)
            * scale
            + offset_y
        )

        return x, y

    return project


def ring_to_path(
    ring: list[list[float]],
    project,
) -> str:
    commands: list[str] = []

    for index, coordinate in enumerate(ring):
        lon, lat = coordinate[:2]
        x, y = project(lon, lat)

        command = "M" if index == 0 else "L"
        commands.append(f"{command}{x:.2f},{y:.2f}")

    commands.append("Z")

    return " ".join(commands)


def main() -> None:
    print("Downloading Natural Earth 1:10m boundary data...")

    request = urllib.request.Request(
        SOURCE_URL,
        headers={"User-Agent": "mydiio-atlas-map-generator/1.0"},
    )

    with urllib.request.urlopen(request, timeout=60) as response:
        data = json.load(response)

    feature = find_sri_lanka(data)
    geometry = feature.get("geometry")

    if not geometry:
        raise RuntimeError("Sri Lanka geometry is missing.")

    rings = extract_rings(geometry)
    project = project_factory(rings)

    path_data = " ".join(
        ring_to_path(ring, project)
        for ring in rings
        if len(ring) >= 4
    )

    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<!--
  Sri Lanka geographic outline
  Source: Natural Earth 1:10m Admin 0 Countries
  Generated by scripts/maps/generate-sri-lanka-svg.py
  Projection: local equirectangular projection centred on Sri Lanka
-->
<svg
  xmlns="http://www.w3.org/2000/svg"
  viewBox="0 0 {VIEWBOX_WIDTH} {VIEWBOX_HEIGHT}"
  role="img"
  aria-labelledby="sri-lanka-map-title sri-lanka-map-description"
>
  <title id="sri-lanka-map-title">
    Sri Lanka network map
  </title>

  <desc id="sri-lanka-map-description">
    An accurate geographic outline of Sri Lanka prepared for the mydiio
    connected passenger network animation.
  </desc>

  <defs>
    <clipPath id="sri-lanka-land-clip">
      <path d="{path_data}" fill-rule="evenodd" />
    </clipPath>

    <filter
      id="sri-lanka-soft-glow"
      x="-30%"
      y="-30%"
      width="160%"
      height="160%"
    >
      <feGaussianBlur stdDeviation="10" result="blur" />
      <feMerge>
        <feMergeNode in="blur" />
        <feMergeNode in="SourceGraphic" />
      </feMerge>
    </filter>
  </defs>

  <g id="sri-lanka-map">
    <path
      id="sri-lanka-land"
      d="{path_data}"
      fill="#FDFAF3"
      fill-rule="evenodd"
      stroke="#D8D2C7"
      stroke-width="3"
      stroke-linejoin="round"
      vector-effect="non-scaling-stroke"
    />

    <!-- Real road geometry will be inserted here from OpenStreetMap data. -->
    <g
      id="sri-lanka-roads"
      clip-path="url(#sri-lanka-land-clip)"
      fill="none"
      stroke="#1A1A18"
      stroke-opacity="0.09"
      stroke-width="1.4"
      vector-effect="non-scaling-stroke"
    />

    <!-- Animated mydiio network connections will be inserted here. -->
    <g
      id="mydiio-network-lines"
      clip-path="url(#sri-lanka-land-clip)"
      fill="none"
      stroke="#F5A623"
      stroke-width="2"
      stroke-linecap="round"
      vector-effect="non-scaling-stroke"
    />

    <!-- Animated mydiio hubs will be inserted here. -->
    <g
      id="mydiio-network-hubs"
      clip-path="url(#sri-lanka-land-clip)"
      filter="url(#sri-lanka-soft-glow)"
    />

    <!-- City labels are rendered separately so they remain legible. -->
    <g
      id="sri-lanka-city-labels"
      font-family="DM Sans, system-ui, sans-serif"
      font-size="22"
      fill="#1A1A18"
      fill-opacity="0.58"
    />
  </g>
</svg>
'''

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(svg, encoding="utf-8")

    print(f"Created {OUTPUT}")
    print(f"SVG paths: {len(rings)}")
    print(f"File size: {OUTPUT.stat().st_size:,} bytes")


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"Map generation failed: {error}", file=sys.stderr)
        raise
