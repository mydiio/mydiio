const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({headless: true});
  const ctx = await browser.newContext({viewport: {width: 1440, height: 900}});
  const page = await ctx.newPage();
  await page.goto('http://127.0.0.1:4173/about', {waitUntil: 'networkidle'});
  await page.waitForTimeout(800);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.waitForTimeout(200);
  await page.screenshot({path: '/tmp/qa-crops/about-fold-0.png'});
  await page.evaluate(() => window.scrollTo(0, 1500));
  await page.waitForTimeout(200);
  await page.screenshot({path: '/tmp/qa-crops/about-fold-1.png'});
  await page.evaluate(() => window.scrollTo(0, 3500));
  await page.waitForTimeout(200);
  await page.screenshot({path: '/tmp/qa-crops/about-fold-2.png'});
  await page.evaluate(() => window.scrollTo(0, 5500));
  await page.waitForTimeout(200);
  await page.screenshot({path: '/tmp/qa-crops/about-fold-3.png'});
  await page.evaluate(() => window.scrollTo(0, 7500));
  await page.waitForTimeout(200);
  await page.screenshot({path: '/tmp/qa-crops/about-fold-4.png'});
  await browser.close();
})().catch(e => console.error(e));
